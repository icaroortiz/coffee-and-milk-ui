#!/usr/bin/env python3
"""Stage the static gallery and built React example for GitHub Pages.

Run npm run build -- --base /coffee-and-milk-ui/react/ in the React example first.
Only staging copies are rewritten; example source stays useful locally.
"""

import argparse
from html.parser import HTMLParser
from pathlib import Path
import re
import shutil
import sys
from urllib.parse import unquote, urlsplit

from repository_files import ROOT

MARKER = ".cafe-com-leite-site"


class LocalLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attributes):
        for name, value in attributes:
            if name in {"href", "src"} and value:
                self.links.append(value)


def validate_site(output, prefix):
    for page in output.rglob("*.html"):
        parser = LocalLinks()
        parser.feed(page.read_text())
        for link in parser.links:
            url = urlsplit(link)
            if url.scheme or url.netloc or not url.path:
                continue
            target = unquote(url.path)
            if target.startswith("/"):
                if not target.startswith(prefix):
                    raise ValueError(f"Wrong Pages base in {page.name}: {target}")
                resolved = (output / target[len(prefix):]).resolve()
            else:
                resolved = (page.parent / target).resolve()
            if not resolved.is_relative_to(output) or not resolved.exists():
                raise ValueError(f"Missing staged asset/link in {page.name}: {link}")
    if not (output / "react/index.html").is_file():
        raise ValueError("React build is missing index.html")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "_site")
    parser.add_argument("--repository", default="icaroortiz/coffee-and-milk-ui")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.repository):
        parser.error("--repository must be owner/repository")
    output = args.output_dir.resolve()
    if output == ROOT or output in ROOT.parents or output.is_relative_to(ROOT / "examples") or output.is_relative_to(ROOT / "skills"):
        parser.error("Choose a separate staging directory, such as _site")
    if output.exists() and not (output / MARKER).is_file():
        parser.error("Output directory already exists without the generated-site marker")
    built = ROOT / "examples/react-shadcn/dist"
    if not (built / "index.html").is_file():
        parser.error("Build the React example before staging (see this script's help)")
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("Generated by scripts/build_site.py; safe to rebuild.\n")

    gallery = ROOT / "examples/gallery"
    html = (gallery / "index.html").read_text()
    replacements = {
        "../../skills/coffee-and-milk-ui/assets/soft-ui.css": "assets/soft-ui.css",
        "../../README.pt-BR.md": f"https://github.com/{args.repository}/blob/main/README.pt-BR.md",
        "../react-shadcn/README.md": "react/",
    }
    for old, new in replacements.items():
        if old not in html:
            raise ValueError(f"Gallery link changed; update staging rule for {old}")
        html = html.replace(old, new)
    (output / "index.html").write_text(html)
    for name in ("gallery.css", "gallery.js"):
        shutil.copy2(gallery / name, output / name)
    (output / "assets").mkdir()
    shutil.copy2(ROOT / "skills/coffee-and-milk-ui/assets/soft-ui.css", output / "assets/soft-ui.css")
    shutil.copytree(built, output / "react")
    (output / ".nojekyll").touch()
    prefix = f"/{args.repository.split('/')[1]}/"
    validate_site(output, prefix)
    print(f"Pages site ready: {output}\nGallery: {prefix}\nReact: {prefix}react/")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as exc:
        print(f"Site staging failed: {exc}", file=sys.stderr)
        sys.exit(1)
